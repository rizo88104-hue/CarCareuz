create index if not exists ix_ltx_center on loyalty_transactions (center_id, created_at);

-- ===== To'lovlar (qarz daftari) =====
create table if not exists payments (
    id bigint generated by default as identity primary key,
    record_id bigint not null references service_records (id),
    center_id bigint not null references service_centers (id),
    amount bigint not null,
    method varchar(20) not null,
    received_by varchar(80),
    note varchar(200),
    created_at timestamp(6) with time zone not null
);
create index if not exists ix_pay_record on payments (record_id);
create index if not exists ix_pay_center on payments (center_id, created_at);

-- ===== Eski bazalar: Hibernate yaratgan enum ustunlarini varchar ga keltirish =====
-- H2 da Hibernate "enum('A','B')" turini, PostgreSQL da varchar(255) + CHECK yaratgan edi; entity lar
-- endi VARCHAR kutadi (validate). SET DATA TYPE ikkala bazada ham ishlaydi; yangi bazada hech narsa o'zgarmaydi.
alter table cars alter column gender set data type varchar(10);
alter table login_requests alter column status set data type varchar(10);
alter table loyalty_accounts alter column level set data type varchar(12);
alter table loyalty_transactions alter column type set data type varchar(20);
alter table payments alter column method set data type varchar(20);
alter table service_records alter column type set data type varchar(30);
alter table staff_users alter column role set data type varchar(20);

-- ===== Servis obunasi (oylik to'lov) =====
create table if not exists subscription_payments (
    id bigint generated by default as identity primary key,
    center_id bigint not null references service_centers (id),
    amount bigint not null,
    months integer not null,
    period_from date not null,
    period_to date not null,
    note varchar(200),
    recorded_by varchar(80),
    created_at timestamp(6) with time zone not null
);
create index if not exists ix_subpay_center on subscription_payments (center_id);
