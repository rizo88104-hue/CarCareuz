create index if not exists ix_log_created on activity_log (created_at);
create index if not exists ix_log_center on activity_log (center_id, created_at);

create table if not exists bot_messages (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    recipient varchar(130),
    plate_number varchar(16),
    text varchar(4096) not null,
    delivered boolean not null default false,
    created_at timestamp(6) with time zone not null
);
create index if not exists ix_botmsg_created on bot_messages (created_at);

-- ===== Mijozlar bazasi (servis izohlari, qora ro'yxat) =====
