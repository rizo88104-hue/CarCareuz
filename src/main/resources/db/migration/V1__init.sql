-- CarCare — boshlang'ich sxema (Flyway V1). H2 va PostgreSQL uchun bir xil.
--
-- Nega hamma joyda IF NOT EXISTS: eski serverlarda bazani Hibernate (ddl-auto=update) yaratgan.
-- Flyway bunday bazani 0-versiya deb belgilaydi (baseline) va shu skriptni bajaradi — mavjud
-- jadvallar o'tkazib yuboriladi, yetishmagan ustunlar qo'shiladi. Yangi bazada hammasi yaratiladi.
-- Keyingi o'zgarishlar: V2__nomi.sql, V3__... (mavjud faylni o'zgartirmang).
--
-- Enum ustunlar varchar — entity larda @JdbcTypeCode(VARCHAR). CHECK cheklovi yo'q: yangi enum qiymati
-- qo'shilganda migratsiya shart emas (qiymatlar Java da tekshiriladi).

-- ===== Avtoservislar =====
create table if not exists service_centers (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    address varchar(200),
    phone varchar(12),
    active boolean not null default true,
    subscription_until date,
    created_at timestamp(6) with time zone not null
);
alter table service_centers add column if not exists subscription_until date;

-- ===== Mashinalar (mijozlar) =====
create table if not exists cars (
    id bigint generated by default as identity primary key,
    token varchar(32) not null,
    first_name varchar(60) not null,
    last_name varchar(60) not null,
    phone varchar(12) not null,
    plate_number varchar(12) not null,
    telegram_chat_id bigint,
    sms_enabled boolean not null default true,
    created_at timestamp(6) with time zone not null,
    lang varchar(2),
    current_mileage integer,
    mileage_updated_at timestamp(6) with time zone,
    mileage_asked_on date,
    birth_date date,
    gender varchar(10),
    source varchar(60),
    birthday_greeted_year integer
);
alter table cars add column if not exists lang varchar(2);
alter table cars add column if not exists current_mileage integer;
alter table cars add column if not exists mileage_updated_at timestamp(6) with time zone;
alter table cars add column if not exists mileage_asked_on date;
alter table cars add column if not exists birth_date date;
alter table cars add column if not exists gender varchar(10);
alter table cars add column if not exists source varchar(60);
alter table cars add column if not exists birthday_greeted_year integer;
create unique index if not exists ux_cars_token on cars (token);
create unique index if not exists ux_cars_plate on cars (plate_number);
create index if not exists ix_cars_chat on cars (telegram_chat_id);

-- ===== Xodimlar =====
create table if not exists staff_users (
    id bigint generated by default as identity primary key,
    username varchar(40) not null,
    password_hash varchar(100) not null,
    role varchar(20) not null,
    full_name varchar(80),
    center_id bigint references service_centers (id),
    blocked boolean,
    created_at timestamp(6) with time zone not null,
    telegram_chat_id bigint,
    lang varchar(2)
);
alter table staff_users add column if not exists telegram_chat_id bigint;
alter table staff_users add column if not exists lang varchar(2);
alter table staff_users add column if not exists blocked boolean;
create unique index if not exists ux_staff_username on staff_users (username);

create table if not exists admin_sessions (
    id bigint generated by default as identity primary key,
    token varchar(48) not null,
    staff_id bigint not null references staff_users (id),
    expires_at timestamp(6) with time zone not null
);
create unique index if not exists ux_admin_sessions_token on admin_sessions (token);

create table if not exists admin_login_codes (
    id bigint generated by default as identity primary key,
    challenge varchar(48) not null,
    staff_id bigint not null references staff_users (id),
    code_hash varchar(64) not null,
    attempts integer not null default 0,
    used boolean not null default false,
    ip varchar(45),
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null
);
create unique index if not exists ix_alc_challenge on admin_login_codes (challenge);

-- ===== Jurnal, bot xabarlari =====
create table if not exists activity_log (
    id bigint generated by default as identity primary key,
    staff_id bigint,
    actor_name varchar(80) not null,
    actor_role varchar(30) not null,
    center_id bigint references service_centers (id),
