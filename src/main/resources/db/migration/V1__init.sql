-- ===== Sadoqat dasturi =====
create table if not exists loyalty_programs (
    id bigint generated by default as identity primary key,
    center_id bigint not null references service_centers (id),
    enabled boolean not null default false,
    silver_from bigint not null default 3000000,
    gold_from bigint not null default 10000000,
    platinum_from bigint not null default 25000000,
    bronze_cashback integer not null default 3,
