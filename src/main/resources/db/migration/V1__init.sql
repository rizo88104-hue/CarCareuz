alter table service_records add column if not exists km_due_sent boolean;
alter table service_records add column if not exists master_name varchar(80);
alter table service_records add column if not exists price bigint;
alter table service_records add column if not exists paid_amount bigint;
alter table service_records add column if not exists pay_due_date date;
alter table service_records add column if not exists credit boolean;
alter table service_records add column if not exists discount bigint;
alter table service_records add column if not exists bonus_paid bigint;
alter table service_records add column if not exists debt_reminded_on date;
alter table service_records add column if not exists ready_notified_at timestamp(6) with time zone;
alter table service_records add column if not exists replaced_at timestamp(6) with time zone;
alter table service_records add column if not exists replaced_by_center_id bigint;
alter table service_records add column if not exists center_id bigint;
